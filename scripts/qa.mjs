import { chromium } from 'playwright';
import { mkdir } from 'node:fs/promises';
import path from 'node:path';

const base = process.env.QA_URL || 'http://localhost:4173/';
const out = path.resolve('screenshots');
await mkdir(out, { recursive: true });
const browser = await chromium.launch({headless:true, executablePath:process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe'});
const issues = [];
const page = await browser.newPage({viewport:{width:1440,height:900}, reducedMotion:'no-preference'});
page.on('pageerror', error => issues.push(`pageerror: ${error.message}`));
page.on('console', msg => { if(msg.type()==='error')issues.push(`console: ${msg.text()}`); });
page.on('response', response => { if(response.status()>=400)issues.push(`http ${response.status()}: ${response.url()}`); });
const snap=async name=>page.screenshot({path:path.join(out,name),animations:'disabled'});
const text=(s)=>page.getByText(s,{exact:false});

await page.goto(base,{waitUntil:'networkidle'});
await snap('opening-desktop.png');
if(!(await text('11 SECONDS MISSING').count()))throw new Error('Opening premise missing');
await page.getByRole('button',{name:/ENTER THE GAP/}).click();
await page.keyboard.press('ArrowRight');
if(!(await text('Intent: hostile.').count()))throw new Error('Keyboard next did not show security');
await snap('security-desktop.png');
await page.keyboard.press('ArrowLeft');
if(!(await text('someone stayed').count()))throw new Error('Keyboard previous did not show romance');
await snap('romance-desktop.png');
await page.getByRole('button',{name:/revolution reconstruction/i}).click();
if(!(await text('city stood up').count()))throw new Error('Revolution scene missing');
await snap('revolution-desktop.png');
await page.getByRole('button',{name:/commerce reconstruction/i}).click();
if(!(await text('€11 / FRAME').count()))throw new Error('Commerce scene missing');
await snap('commerce-desktop.png');
await page.getByRole('button',{name:/PAUSE/}).click();
if(!(await page.getByRole('button',{name:/PLAY/}).count()))throw new Error('Pause did not toggle');
await page.getByRole('button',{name:/PLAY/}).click();
await page.getByRole('button',{name:/Enable sound/}).click();
if(!(await page.getByRole('button',{name:/Mute sound/}).count()))throw new Error('Sound toggle did not enable');
await page.getByRole('button',{name:/SHOW ORIGINAL FOOTAGE/}).click();
if(!(await text('ORIGINAL FRAMES').count())||!(await text('YOU HAVE SEEN NONE OF IT').count()))throw new Error('Original reveal incomplete');
await snap('original-desktop.png');
await page.getByRole('button',{name:/REPLAY/}).click();
if(!(await text('11 SECONDS MISSING').count()))throw new Error('Replay did not return to opening');
await page.reload({waitUntil:'networkidle'});
if(!(await text('11 SECONDS MISSING').count()))throw new Error('Hard refresh failed');
await page.emulateMedia({reducedMotion:'reduce'});
const reduced = await page.locator('.vision').evaluate(el=>getComputedStyle(el).animationDuration);

await page.setViewportSize({width:390,height:844});
await page.reload({waitUntil:'networkidle'});
await snap('opening-mobile.png');
const mobileOverflow=await page.evaluate(()=>({width:document.documentElement.scrollWidth,viewport:innerWidth,stage:document.querySelector('.stage')?.getBoundingClientRect().width}));
await page.getByRole('button',{name:/ENTER THE GAP/}).click();
await page.getByRole('button',{name:/SHOW ORIGINAL FOOTAGE/}).click();
await snap('original-mobile.png');
if(mobileOverflow.width>mobileOverflow.viewport)issues.push(`mobile horizontal overflow: ${JSON.stringify(mobileOverflow)}`);
await page.setViewportSize({width:768,height:1024});
await page.getByRole('button',{name:/REPLAY/}).click();
await page.getByRole('button',{name:/security reconstruction/i}).click();
await snap('security-tablet.png');
const tabletOverflow=await page.evaluate(()=>({width:document.documentElement.scrollWidth,viewport:innerWidth}));
if(tabletOverflow.width>tabletOverflow.viewport)issues.push(`tablet horizontal overflow: ${JSON.stringify(tabletOverflow)}`);
const externalRequests=await page.evaluate(()=>performance.getEntriesByType('resource').map(r=>r.name).filter(n=>!n.startsWith(location.origin)&&!n.startsWith('data:')));
await browser.close();
console.log(JSON.stringify({base,desktopViewport:'1440x900',tabletViewport:'768x1024',mobileViewport:'390x844',mobileOverflow,tabletOverflow,reducedMotionAnimationDuration:reduced,externalRequests,screenshots:await (await import('node:fs/promises')).readdir(out),issues},null,2));
if(issues.length)process.exitCode=1;
